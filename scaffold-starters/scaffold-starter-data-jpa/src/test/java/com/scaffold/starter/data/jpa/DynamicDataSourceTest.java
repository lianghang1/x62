package com.scaffold.starter.data.jpa;

import com.scaffold.starter.data.jpa.datasource.DynamicRoutingDataSource;
import com.scaffold.starter.data.jpa.datasource.TargetDataSource;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.autoconfigure.SpringBootApplication;
import org.springframework.context.annotation.Bean;
import org.springframework.boot.jdbc.DataSourceBuilder;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

import javax.sql.DataSource;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * 动态数据源集成测试：master/slave 两个 H2 内存库，验证注解切换、事务边界、fail-fast。
 *
 * <p>建表分工：master 的表由 Hibernate ddl-auto 创建（EMF 拿到的是路由数据源，
 * 首个连接即主库）；slave 的表在 {@code @BeforeAll} 用裸连接手工建——两边是
 * 独立的 H2 内存库，schema 互不可见，天然隔离。</p>
 *
 * @author lianghang
 */
@SpringBootTest(classes = DynamicDataSourceTest.TestApp.class, properties = {
        "scaffold.datasource.dynamic.enabled=true",
        "scaffold.datasource.dynamic.primary=master",
        "scaffold.datasource.dynamic.datasources.master.url=" + DynamicDataSourceTest.MASTER_URL,
        "scaffold.datasource.dynamic.datasources.master.driver-class-name=org.h2.Driver",
        "scaffold.datasource.dynamic.datasources.slave.url=" + DynamicDataSourceTest.SLAVE_URL,
        "scaffold.datasource.dynamic.datasources.slave.driver-class-name=org.h2.Driver",
        "spring.jpa.hibernate.ddl-auto=create-drop"
})
class DynamicDataSourceTest {

    static final String MASTER_URL = "jdbc:h2:mem:dyn_master;DB_CLOSE_DELAY=-1";
    static final String SLAVE_URL = "jdbc:h2:mem:dyn_slave;DB_CLOSE_DELAY=-1";

    @Autowired
    DataSource dataSource;

    @Autowired
    DynRecordRepository repository;

    @Autowired
    RecordService service;

    @Autowired
    SlaveAnnotatedService slaveAnnotatedService;

    @BeforeAll
    static void createSlaveTable() {
        DataSource slave = DataSourceBuilder.create().url(SLAVE_URL)
                .driverClassName("org.h2.Driver").build();
        new JdbcTemplate(slave).execute("CREATE TABLE IF NOT EXISTS DYN_RECORD "
                + "(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(255))");
    }

    @BeforeEach
    void truncateBothDatabases() {
        // Spring 上下文跨测试缓存且 H2 常驻内存，先清空两库保证各用例计数从零开始
        new JdbcTemplate(DataSourceBuilder.create().url(MASTER_URL)
                .driverClassName("org.h2.Driver").build()).update("DELETE FROM DYN_RECORD");
        new JdbcTemplate(DataSourceBuilder.create().url(SLAVE_URL)
                .driverClassName("org.h2.Driver").build()).update("DELETE FROM DYN_RECORD");
    }

    @Test
    void routingDataSourceShouldBeInstalled() {
        assertThat(dataSource).isInstanceOf(DynamicRoutingDataSource.class);
    }

    @Test
    void withoutAnnotationShouldRouteToPrimary() {
        repository.save(new DynRecord("a1"));
        assertThat(masterCount()).isEqualTo(1);
        assertThat(slaveCount()).isEqualTo(0);
    }

    @Test
    void annotatedMethodShouldRouteToSlave() {
        service.saveSlave(new DynRecord("s1"));
        assertThat(slaveCount()).isEqualTo(1);
        assertThat(masterCount()).isEqualTo(0);
    }

    @Test
    void transactionalMethodShouldStillRouteToSlave() {
        // 切面为最高优先级：先于事务拦截器压栈，事务内的连接获取走 slave
        service.saveSlaveInTx(new DynRecord("t1"));
        assertThat(slaveCount()).isEqualTo(1);
        assertThat(masterCount()).isEqualTo(0);
    }

    @Test
    void classLevelAnnotationShouldRouteToSlave() {
        slaveAnnotatedService.save(new DynRecord("c1"));
        assertThat(slaveCount()).isEqualTo(1);
        assertThat(masterCount()).isEqualTo(0);
    }

    @Test
    void contextShouldBeRestoredAfterAnnotatedCall() {
        service.saveSlave(new DynRecord("r1"));
        repository.save(new DynRecord("r2"));
        assertThat(masterCount()).isEqualTo(1);
        assertThat(slaveCount()).isEqualTo(1);
    }

    @Test
    void unknownKeyShouldFailFast() {
        assertThatThrownBy(() -> service.saveUnknown(new DynRecord("x1")))
                .isInstanceOf(IllegalStateException.class)
                .hasMessageContaining("nope");
        assertThat(slaveCount()).isEqualTo(0);
        assertThat(masterCount()).isEqualTo(0);
    }

    private int masterCount() {
        return rawCount(MASTER_URL);
    }

    private int slaveCount() {
        return rawCount(SLAVE_URL);
    }

    private int rawCount(String url) {
        DataSource raw = DataSourceBuilder.create().url(url)
                .driverClassName("org.h2.Driver").build();
        return new JdbcTemplate(raw)
                .queryForObject("SELECT COUNT(*) FROM DYN_RECORD", Integer.class);
    }

    @SpringBootApplication
    static class TestApp {

        @Bean
        RecordService recordService() {
            return new RecordService();
        }

        @Bean
        SlaveAnnotatedService slaveAnnotatedService() {
            return new SlaveAnnotatedService();
        }
    }

    static class RecordService {

        @Autowired
        DynRecordRepository repository;

        @TargetDataSource("slave")
        public DynRecord saveSlave(DynRecord record) {
            return repository.save(record);
        }

        @TargetDataSource("slave")
        @Transactional("transactionManager")
        public DynRecord saveSlaveInTx(DynRecord record) {
            return repository.save(record);
        }

        @TargetDataSource("nope")
        public DynRecord saveUnknown(DynRecord record) {
            return repository.save(record);
        }
    }

    @TargetDataSource("slave")
    static class SlaveAnnotatedService {

        @Autowired
        DynRecordRepository repository;

        public DynRecord save(DynRecord record) {
            return repository.save(record);
        }
    }
}
